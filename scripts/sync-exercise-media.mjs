import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import { MEDIA_REVISIONS, MEDIA_SOURCES } from '../src/exerciseMediaSources.ts'

const root = fileURLToPath(new URL('../', import.meta.url))
const destination = join(root, 'public', 'exercises')
const licenseUrl = 'https://creativecommons.org/licenses/by-sa/4.0/'
const originalBase = `https://raw.githubusercontent.com/everkinetic/data/${MEDIA_REVISIONS.everkinetic}`
const guideBase = `https://raw.githubusercontent.com/bryllim/workout-guide/${MEDIA_REVISIONS.guide}/packages/workout-guide`

async function fetchText(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(30000) })
  if (!response.ok) throw new Error(`Download failed: ${response.status} ${url}`)
  return response.text()
}

function validateSvg(svg, url) {
  if (!svg.includes('<svg') || /<script\b|<foreignObject\b|\bon\w+\s*=|(?:href|src)\s*=\s*["'](?:https?:|\/\/)/i.test(svg)) {
    throw new Error(`Unexpected or externally linked SVG: ${url}`)
  }
}

const original = JSON.parse(await fetchText(`${originalBase}/exercises.json`))
const guide = JSON.parse(await fetchText(`${guideBase}/manifest.json`))
const tree = JSON.parse(await fetchText(`https://api.github.com/repos/everkinetic/data/git/trees/${MEDIA_REVISIONS.everkinetic}?recursive=1`))
if (tree.truncated) throw new Error('The original asset tree is incomplete.')
const originalFiles = new Set(tree.tree.map((item) => item.path))
await mkdir(destination, { recursive: true })
const registry = {}
const downloaded = new Set()

for (const [exerciseId, source] of Object.entries(MEDIA_SOURCES)) {
  let title
  let frames
  if (source.provider === 'everkinetic') {
    const entry = original.find((item) => item.id_num === source.id)
    if (!entry) throw new Error(`Original exercise missing: ${source.id}`)
    title = entry.title
    frames = ['tension', 'relaxation'].map((pose, index) => {
      const candidates = [`dist/svg/${source.id}-${pose}.svg`]
      const webImage = entry.img?.[index]
      if (webImage) candidates.push(`src/images-web/${webImage.split('/').at(-1)}`)
      const path = candidates.find((candidate) => originalFiles.has(candidate))
      if (!path) throw new Error(`No exact illustration found for ${source.id}, pose ${index + 1}`)
      return {
        file: `everkinetic-${source.id}-${index + 1}.${path.endsWith('.svg') ? 'svg' : 'png'}`,
        url: `${originalBase}/${path}`,
        sourceUrl: `https://github.com/everkinetic/data/blob/${MEDIA_REVISIONS.everkinetic}/${path}`,
        creator: 'Everkinetic / Greg Priday', creatorUrl: 'https://github.com/everkinetic/data',
        license: 'CC BY-SA 4.0', licenseUrl, changes: 'File originale, non modificato.',
      }
    })
  } else {
    const entry = guide.find((item) => item.slug === source.id)
    if (!entry) throw new Error(`Guide exercise missing: ${source.id}`)
    title = entry.name
    // One static pose is sufficient for identification; do not imply a validated animation.
    frames = entry.frames.slice(0, 1).map((frame) => {
      if (frame.attribution.licenseUrl !== licenseUrl) throw new Error(`Unexpected asset license: ${entry.slug}`)
      return {
        file: `guide-${entry.slug}-${frame.index}.svg`, url: `${guideBase}/${frame.path}`,
        sourceUrl: `https://github.com/bryllim/workout-guide/blob/${MEDIA_REVISIONS.guide}/packages/workout-guide/${frame.path}`,
        creator: frame.attribution.creator, creatorUrl: frame.attribution.creatorUrl,
        license: frame.attribution.license, licenseUrl,
        changes: 'File originale, non modificato. Colori invertiti solo nella visualizzazione.',
        ...(frame.attribution.source ? { original: frame.attribution.source } : {}),
      }
    })
  }
  for (const frame of frames) {
    if (downloaded.has(frame.file)) continue
    const response = await fetch(frame.url, { signal: AbortSignal.timeout(30000) })
    if (!response.ok) throw new Error(`Download failed: ${response.status} ${frame.url}`)
    const bytes = Buffer.from(await response.arrayBuffer())
    if (frame.file.endsWith('.svg')) validateSvg(bytes.toString('utf8'), frame.url)
    else if (bytes.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a') throw new Error(`Invalid PNG: ${frame.url}`)
    await writeFile(join(destination, frame.file), bytes)
    downloaded.add(frame.file)
  }
  registry[exerciseId] = { title, invert: source.provider === 'guide', frames }
}

await writeFile(join(destination, 'LICENSE-CC-BY-SA-4.0.txt'), await fetchText(`${originalBase}/LICENSE.md`))
await writeFile(join(destination, 'ATTRIBUTION.json'), JSON.stringify({ revisions: MEDIA_REVISIONS, images: registry }, null, 2) + '\n')
await writeFile(join(root, 'src', 'exerciseMedia.generated.ts'),
  '// Generated by scripts/sync-exercise-media.mjs. Do not edit by hand.\n'
  + "import type { ExerciseMedia } from './exerciseMedia.ts'\n"
  + `export const EXERCISE_MEDIA: Readonly<Record<string, ExerciseMedia>> = ${JSON.stringify(registry, null, 2)}\n`)
console.log(`Downloaded ${downloaded.size} illustrations for ${Object.keys(registry).length} exercise variants.`)
